// Apostrophes: STT may output ' or the curly ’. Covers "I'm X", "I am X", "my name is X",
// "my name's X", "name's X", "this is X", "call me X", "you can call me X".
final _selfIntro = RegExp(
  r"\b(?:i['’]m|i am|my name(?:['’]s| is)|name['’]s|this is|call me)\s+([a-z][a-z'’\-]*)",
  caseSensitive: false,
);
final _calledAtStart = RegExp(
  r"^\s*([a-z][a-z'\-]*)\s*,",
  caseSensitive: false,
);
final _calledAtEnd = RegExp(
  r",\s*([a-z][a-z'\-]*)\s*\?\s*$",
  caseSensitive: false,
);

String? _asName(String? token) {
  if (token == null || token.length < 2) return null;
  final lower = token.toLowerCase();
  if (_stopwords.contains(lower)) return null;
  return lower[0].toUpperCase() + lower.substring(1);
}

/// "I'm Zairus" -> "Zairus": the speaker of this line is named.
String? selfIntroName(String text) =>
    _asName(_selfIntro.firstMatch(text)?.group(1));

/// "Sam, can you…" / "…what do you think, Sam?" -> "Sam": the next
/// different known speaker is named.
String? calledName(String text) =>
    _asName(_calledAtStart.firstMatch(text)?.group(1)) ??
    _asName(_calledAtEnd.firstMatch(text)?.group(1));
